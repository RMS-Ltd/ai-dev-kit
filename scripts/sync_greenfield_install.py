"""
Sync maintainer sources into greenfield-install/ (FR-110 / E06:S09:T21).

Idempotent copy of packages/frameworks/ plus generated adopter README and footprint
report. Use --check in CI to fail when sources change without re-sync.
"""

from __future__ import annotations

import argparse
import fnmatch
import hashlib
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Iterable, List, Tuple

